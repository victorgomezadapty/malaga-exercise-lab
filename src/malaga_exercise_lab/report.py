"""Write RESULTS.md from the locked summary and aggregate tables."""
from __future__ import annotations

from pathlib import Path

import pandas as pd


def f1(x, k=1):
    out = f"{x:.{k}f}"
    return out[1:] if out.startswith("-") and float(out) == 0 else out


def ci(lo, hi, k=1):
    return f"{f1(lo, k)} to {f1(hi, k)}"


def err_table(t: pd.DataFrame, with_sample: bool = False) -> str:
    head = ("| Sample | " if with_sample else "| ") + "Formula | n tests | Bias, bpm (95% CI) | MAE, bpm (95% CI) | RMSE, bpm (95% CI) | abs error > 10 bpm, % (95% CI) |"
    sep = "|-" * (head.count("|") - 1) + "|"
    lines = [head, sep]
    for r in t.itertuples():
        pre = f"| {r.sample} | " if with_sample else "| "
        lines.append(pre + f"{r.formula} ({r.formula_text}) | {r.n_tests} | {f1(r.bias_bpm)} ({ci(r.bias_ci95_low, r.bias_ci95_high)}) | "
                     f"{f1(r.mae_bpm)} ({ci(r.mae_ci95_low, r.mae_ci95_high)}) | {f1(r.rmse_bpm)} ({ci(r.rmse_ci95_low, r.rmse_ci95_high)}) | "
                     f"{f1(r.pct_abs_error_over_10)} ({ci(r.pct_ci95_low, r.pct_ci95_high)}) |")
    return "\n".join(lines)


def write_results_md(path: Path, S: dict, cmp_df, flags, prim, sens, minors, sub, shifts, disc, desc, band) -> None:
    n = S["samples"]
    al = S["age_line_descriptive"]
    L = []
    L.append("# Results\n")
    L.append("Generated by `scripts/run_analysis.py` from the verified deposit files. Do not edit by hand; "
             "numbers are locked in `results/summary.json`. Local unpublished draft. Aggregates only.\n")
    L.append(f"Source: {S['dataset']['citation']}. License file CC BY-NC-SA 4.0; project card lists the "
             "PhysioNet Contributor Review Health Data License 1.5.0 (see DATA_LICENSE.md).\n")
    L.append("## Primary result\n")
    L.append(f"Primary sample: adults (18 and over), first test per person, n = {n['primary']} tests from "
             f"{n['primary']} people. Error = formula HRmax minus observed effort phase HRpeak.\n")
    L.append(err_table(prim) + "\n")
    p = prim.set_index("formula")
    L.append(f"220 minus age sits on average {f1(p.loc['220 minus age','bias_bpm'])} bpm above the observed peak. "
             f"Tanaka and Gellish are close to zero on average (bias {f1(p.loc['Tanaka 2001','bias_bpm'])} and "
             f"{f1(p.loc['Gellish 2007','bias_bpm'])} bpm), but still miss a single person by "
             f"{f1(p.loc['Tanaka 2001','mae_bpm'])} and {f1(p.loc['Gellish 2007','mae_bpm'])} bpm on average, and by more than "
             f"10 bpm in {f1(p.loc['Tanaka 2001','pct_abs_error_over_10'])}% and {f1(p.loc['Gellish 2007','pct_abs_error_over_10'])}% of tests. "
             "A small average bias does not make the formula accurate for an individual.\n")
    L.append("## Zone shift and zone discordance (primary sample)\n")
    L.append("Zones: below 70%, 70 to 85%, above 85% of HRmax. Shift = boundary from the formula minus boundary from observed HRpeak.\n")
    L.append("| Formula | Boundary | Mean shift, bpm (95% CI) | Median | 10th to 90th percentile | tests with shift > 5 bpm, % |\n|-|-|-|-|-|-|")
    for r in shifts.itertuples():
        L.append(f"| {r.formula} | {r.boundary_pct_hrmax}% | {f1(r.mean_shift_bpm)} ({ci(r.ci95_low, r.ci95_high)}) | {f1(r.median_shift_bpm)} | "
                 f"{f1(r.p10_shift_bpm)} to {f1(r.p90_shift_bpm)} | {f1(r.pct_tests_shift_over_5bpm)} |")
    L.append("")
    L.append("| Formula | Effort time with a different zone, mean % per test (95% CI) | Median % | Formula zone lower, % | Formula zone higher, % | tests with > 10% of time discordant, % |\n|-|-|-|-|-|-|")
    for r in disc.itertuples():
        L.append(f"| {r.formula} | {f1(r.mean_pct_time_discordant)} ({ci(r.ci95_low, r.ci95_high)}) | {f1(r.median_pct_time_discordant)} | "
                 f"{f1(r.mean_pct_time_formula_lower_zone)} | {f1(r.mean_pct_time_formula_higher_zone)} | {f1(r.pct_tests_over_10pct_time_discordant)} |")
    L.append(f"\nPooled effort time: {disc['effort_hours'].iloc[0]:.1f} hours. This describes how often the label changes; it is "
             "not training advice and not evidence that any formula is equivalent to a measured peak.\n")
    L.append("## Sensitivity analyses (labelled, not primary)\n")
    L.append(err_table(sens, with_sample=True) + "\n")
    L.append("## Descriptive only\n")
    L.append("Under 18, first test per person. Not pooled into the primary family; the formulas were built for adults.\n")
    L.append(err_table(minors) + "\n")
    L.append("Primary sample by age band and by sex (descriptive).\n")
    L.append(err_table(sub.assign(sample=sub["subgroup"]), with_sample=True) + "\n")
    L.append(f"Descriptive OLS line of observed HRpeak on age in the primary sample (HC3): intercept {al['intercept']:.1f} "
             f"({ci(*al['intercept_ci95'])}), slope {al['slope_per_year']:.2f} bpm per year ({ci(*al['slope_ci95'], k=2)}), "
             f"residual SD {al['residual_sd_bpm']:.1f} bpm, R2 {al['r2']:.2f}. This is a description of this open table, "
             "not a proposed formula.\n")
    L.append("Observed HRpeak by age band (primary sample, bands under 10 tests suppressed).\n")
    L.append("| Age band | n | Observed HRpeak mean (95% CI) | Bias 220 minus age | Bias Tanaka | Bias Gellish |\n|-|-|-|-|-|-|")
    for r in band.to_dict("records"):
        if r["suppressed"]:
            L.append(f"| {r['age_band']} | under 10 | suppressed | | | |")
        else:
            L.append(f"| {r['age_band']} | {r['n_tests']} | {f1(r['observed_hrpeak_mean'])} ({ci(r['ci95_low'], r['ci95_high'])}) | "
                     f"{f1(r['bias_220 minus age'])} | {f1(r['bias_Tanaka 2001'])} | {f1(r['bias_Gellish 2007'])} |")
    L.append("\nPrimary sample descriptors.\n")
    L.append("| Variable | n | Mean | SD | Median | Q1 | Q3 |\n|-|-|-|-|-|-|-|")
    for r in desc.itertuples():
        L.append(f"| {r.variable} | {r.n} | {r.mean:.1f} | {r.sd:.1f} | {r.median:.1f} | {r.q1:.1f} | {r.q3:.1f} |")
    L.append("\nVO2peak is a descriptor only (highest 30 s mean during the effort phase, tests with gas data).\n")
    L.append("## Effort phase rule outcomes\n")
    ph = S["effort_phase"]
    names = {"flag_warmup_not_5kmh": "warmup speed outside 4.5 to 5.5 km/h", "flag_effort_short": "effort phase under 180 s",
             "flag_drop_inside_effort": "speed drop of 1 km/h or more inside the effort phase", "flag_no_recovery": "no recovery samples",
             "flag_recovery_not_5kmh": "recovery median speed outside 3.5 to 5.5 km/h"}
    L.append("| Irregular protocol flag | Tests (all 992) |\n|-|-|")
    for k, v in ph["flag_counts_all_tests"].items():
        L.append(f"| {names[k]} | {v} |")
    L.append(f"\nAny flag: {ph['irregular_all_tests']} tests ({ph['irregular_primary']} in the primary sample). The any time maximum "
             f"exceeds the effort phase maximum in {ph['hrpeak_in_recovery_primary']} primary tests, that is, the highest value fell "
             "outside the effort phase window.\n")
    L.append("## Audit of the deposit\n")
    L.append("| Item | Deposit page | Files | Match |\n|-|-|-|-|")
    for r in cmp_df.itertuples():
        L.append(f"| {r.item} | {r.deposit_page} | {r.files} | {r.match} |")
    L.append("\n| Flag | Severity | Item | Detail |\n|-|-|-|-|")
    for r in flags.itertuples():
        L.append(f"| {r.flag} | {r.severity} | {r.item} | {r.detail} |")
    L.append("\nNo value in the deposited files was changed. HR values below 30 bpm are set to missing in memory only.\n")
    L.append("## Methods in brief\n")
    L.append("Plan fixed in ANALYSIS_PLAN.md before results. Bias and MAE CI: intercept only OLS with HC3 (cluster robust by "
             "person when several tests per person). RMSE CI: percentile bootstrap, 2000 resamples, seed 20261111. Share above 10 bpm: "
             "Wilson interval (person cluster bootstrap with several tests per person). Zone time weights: time to the next sample, "
             "capped at 10 s.\n")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
